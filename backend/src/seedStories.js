require("dotenv").config();
const { PrismaClient } = require("@prisma/client");

const prisma = new PrismaClient();

async function main() {
  const existing = await prisma.story.count();
  if (existing > 0) {
    console.log("Stories already exist, skip seeding.");
    return;
  }

  const stories = [
    {
      title: "Первые две недели: почему чувство одиночества — это нормально",
      topic: "социальная адаптация",
      preview: "Что я чувствовал(а) в начале и какие маленькие шаги помогли…",
      body:
        "В первые две недели мне казалось, что у всех уже есть друзья, а я один/одна. " +
        "На самом деле многие просто стараются выглядеть уверенно. Мне помогло: " +
        "1) написать в общий чат и спросить про расписание, 2) сходить на одно мероприятие факультета, " +
        "3) выбрать 1–2 человека и предложить вместе дойти до пары. " +
        "Постепенно стало легче — главное не требовать от себя «сразу друзей на всю жизнь».",
    },
    {
      title: "Как я перестал(а) бояться задавать вопросы преподавателям",
      topic: "учёба и тревожность",
      preview: "Иногда страшно показаться «глупым», но это лечится практикой…",
      body:
        "Я долго молчал(а) на парах, потому что боялся(ась) ошибиться. Потом понял(а), что преподаватели " +
        "обычно ценят уточнения. Я начал(а) с простого: задавал(а) вопрос после пары или в чате. " +
        "Ещё помогло заранее записывать вопрос на бумагу — так проще начать. С каждым разом тревоги становилось меньше.",
    },
    {
      title: "Если не совпал(а) с группой: что можно сделать",
      topic: "общение",
      preview: "Иногда «свои» люди находятся не сразу и не только в группе…",
      body:
        "Бывает, что в группе нет близких по интересам людей — это нормально. Мне помогло искать окружение " +
        "в кружках, студсовете и через общие активности. Даже один знакомый с параллели может сильно поддержать. " +
        "Плюс: отношения в группе часто улучшаются ближе к сессии, когда вы проходите через общие сложности.",
    },
  ];

  await prisma.story.createMany({
    data: stories.map((s) => ({ ...s, status: "APPROVED" })),
  });

  console.log("Seeded stories:", stories.length);
}

main()
  .catch(console.error)
  .finally(async () => prisma.$disconnect());